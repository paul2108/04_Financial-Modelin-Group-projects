"""Export the strategy core from the notebook into app/strategy_core.py.

The notebook is the single source of truth: every code cell tagged "core" is copied, in order,
into app/strategy_core.py, which the Streamlit app and the tests import. This keeps the app's
calculations identical to the notebook's. The imports come from the cell tagged "imports"
("# Import packages"); only the ones the core code uses are written to the top of the module.

Usage:
    python tools/export_core.py            # write app/strategy_core.py
    python tools/export_core.py --dry-run  # show what would change, write nothing
    python tools/export_core.py --check    # exit code 1 if app/strategy_core.py is out of date
"""

import argparse
import ast
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebook" / "GroupZ_RiskParity_Trend.ipynb"
TARGET = ROOT / "app" / "strategy_core.py"

HEADER = '''"""Strategy core of the Group Z prospectus "Risk Parity + Trend".

AUTO-GENERATED from notebook/GroupZ_RiskParity_Trend.ipynb (cells tagged "core")
by tools/export_core.py. Do not edit this file by hand: change the notebook and run `make core`.
"""
'''


def cells_tagged(nb: dict, tag: str) -> list[str]:
    """Source code of all code cells carrying `tag`, in notebook order."""
    out = []
    for cell in nb["cells"]:
        if cell["cell_type"] == "code" and tag in cell.get("metadata", {}).get("tags", []):
            src = "".join(cell["source"]) if isinstance(cell["source"], list) else cell["source"]
            out.append(src.strip("\n"))
    return out


def import_block(nb: dict, core_src: str) -> str:
    """Import statements from the cell tagged "imports" that the core code actually uses.

    All packages are imported once at the top of the notebook ("# Import packages"). The core
    module only needs the subset its functions refer to (e.g. not matplotlib or quantstats).
    """
    cells = cells_tagged(nb, "imports")
    if not cells:
        raise SystemExit("no cell tagged 'imports' found in the notebook")
    used = {n.id for n in ast.walk(ast.parse(core_src)) if isinstance(n, ast.Name)}
    stdlib, third_party = [], []
    for src in cells:
        for node in ast.parse(src).body:
            if not isinstance(node, (ast.Import, ast.ImportFrom)):
                continue
            bound = {(a.asname or a.name).split(".")[0] for a in node.names}
            if bound & used:
                module = (node.module if isinstance(node, ast.ImportFrom) else node.names[0].name).split(".")[0]
                group = stdlib if module in sys.stdlib_module_names else third_party
                group.append(ast.get_source_segment(src, node))
    return "\n\n".join("\n".join(g) for g in (stdlib, third_party) if g)


def build_core(notebook: Path = NOTEBOOK) -> str:
    nb = json.loads(notebook.read_text(encoding="utf-8"))
    parts = cells_tagged(nb, "core")
    if not parts:
        raise SystemExit(f"no cells tagged 'core' found in {notebook}")
    core_src = "\n\n\n".join(parts)
    return HEADER + "\n" + import_block(nb, core_src) + "\n\n\n" + core_src + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="show the diff, write nothing")
    parser.add_argument("--check", action="store_true", help="fail if the target is out of date")
    args = parser.parse_args()

    new = build_core()
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if new == old:
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0
    if args.check:
        print(f"{TARGET.relative_to(ROOT)} is OUT OF DATE - run `make core`")
        return 1
    if args.dry_run:
        diff = difflib.unified_diff(old.splitlines(), new.splitlines(), "current", "from notebook", lineterm="")
        print("\n".join(diff) or "(new file)")
        print("\n--dry-run: nothing written")
        return 0
    TARGET.write_text(new, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(new.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
