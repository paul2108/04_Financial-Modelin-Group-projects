"""Export the strategy core from the notebook into app/strategy_core.py.

The notebook is the single source of truth: every code cell tagged "core" is copied, in order,
into app/strategy_core.py, which the Streamlit app and the tests import. This keeps the app's
calculations identical to the notebook's.

Usage:
    python tools/export_core.py            # write app/strategy_core.py
    python tools/export_core.py --dry-run  # show what would change, write nothing
    python tools/export_core.py --check    # exit code 1 if app/strategy_core.py is out of date
"""

import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebook" / "GroupZ_RiskParity_Trend.ipynb"
TARGET = ROOT / "app" / "strategy_core.py"

HEADER = '''"""Strategy core of the Group Z prospectus "Risk Parity + Trend".

AUTO-GENERATED from notebook/GroupZ_RiskParity_Trend.ipynb (cells tagged "core")
by tools/export_core.py. Do not edit this file by hand: change the notebook and run `make core`.
"""
'''


def build_core(notebook: Path = NOTEBOOK) -> str:
    nb = json.loads(notebook.read_text(encoding="utf-8"))
    parts = []
    for cell in nb["cells"]:
        if cell["cell_type"] == "code" and "core" in cell.get("metadata", {}).get("tags", []):
            src = "".join(cell["source"]) if isinstance(cell["source"], list) else cell["source"]
            parts.append(src.strip("\n"))
    if not parts:
        raise SystemExit(f"no cells tagged 'core' found in {notebook}")
    return HEADER + "\n\n" + "\n\n\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="show the diff, write nothing")
    parser.add_argument("--check", action="store_true", help="fail if the target is out of date")
    args = parser.parse_args()

    new = build_core()
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if new == old:
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0
    if args.check:
        print(f"{TARGET.relative_to(ROOT)} is OUT OF DATE - run `make core`")
        return 1
    if args.dry_run:
        diff = difflib.unified_diff(old.splitlines(), new.splitlines(), "current", "from notebook", lineterm="")
        print("\n".join(diff) or "(new file)")
        print("\n--dry-run: nothing written")
        return 0
    TARGET.write_text(new, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(new.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
