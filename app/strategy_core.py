# ---------------------------------------------------------------- extract
def download_prices(tickers, start, end, retries=3, pause=5.0):
    """EXTRACT: daily split- and dividend-adjusted close prices from Yahoo Finance.

    One batched yfinance call (fewer requests -> fewer rate-limit problems); `end` is exclusive.
    The columns come back in the order of `tickers` (yfinance itself sorts them alphabetically).
    """
    tickers = list(tickers)
    last_error = None
    for attempt in range(1, retries + 1):
        try:
            raw = yf.download(tickers, start=start, end=end, interval="1d",
                              auto_adjust=True, progress=False, threads=True)
            if raw is not None and not raw.empty:
                close = raw["Close"]
                if isinstance(close, pd.Series):          # single ticker -> Series
                    close = close.to_frame(tickers[0])
                close = close.reindex(columns=tickers)
                missing = [t for t in tickers if close[t].notna().sum() == 0]
                if not missing:
                    return close
                last_error = RuntimeError(f"no data returned for {missing}")
        except Exception as exc:                          # network / rate-limit errors
            last_error = exc
        if attempt < retries:
            time.sleep(pause * attempt)
    raise RuntimeError(f"Download from Yahoo Finance failed after {retries} attempts: {last_error}")


# ---------------------------------------------------------------- transform & load
@dataclass
class MarketData:
    """LOAD: the clean, aligned data that every later step reads."""
    prices_d: pd.DataFrame   # daily adjusted close prices (all tickers incl. ^IRX yield)
    rets_d: pd.DataFrame     # daily simple returns of the tradable tickers
    prices_m: pd.DataFrame   # month-end prices of the tradable tickers
    rets_m: pd.DataFrame     # monthly simple returns, labelled with the month they are earned in
    rf_m: pd.Series          # risk-free return earned in month t (known at the end of month t-1)


def clean_prices(raw):
    """TRANSFORM: tz-naive sorted daily index without duplicates or empty rows."""
    p = raw.copy()
    p.index = pd.to_datetime(p.index)
    if p.index.tz is not None:
        p.index = p.index.tz_localize(None)
    p = p[~p.index.duplicated(keep="last")].sort_index()
    return p.dropna(how="all")


def to_month_end(prices):
    """Last available daily observation of every calendar month (labelled with the month-end date)."""
    return prices.resample("ME").last()


def rf_from_irx(irx):
    """^IRX (13-week T-bill yield, % p.a.) -> monthly cash return earned in the FOLLOWING month."""
    irx_m = to_month_end(irx.ffill(limit=5))
    return (irx_m / 1200).shift(1).rename("rf")


def build_market_data(prices_raw, risky, others, rf_ticker="^IRX"):
    """TRANSFORM + LOAD: everything the strategy, benchmarks and metrics need."""
    p = clean_prices(prices_raw)
    tradables = list(risky) + list(others)
    prices_d = p[tradables + [rf_ticker]]
    rets_d = prices_d[tradables].pct_change(fill_method=None)
    prices_m = to_month_end(prices_d[tradables])
    rets_m = prices_m.pct_change(fill_method=None)
    rf_m = rf_from_irx(prices_d[rf_ticker]).reindex(prices_m.index)
    return MarketData(prices_d=prices_d, rets_d=rets_d, prices_m=prices_m, rets_m=rets_m, rf_m=rf_m)


# ---------------------------------------------------------------- strategy: risk parity weights
def inverse_vol_weights(cov):
    """Weights proportional to 1/volatility (the ERC solution when correlations are zero)."""
    iv = 1.0 / np.sqrt(np.diag(np.asarray(cov, dtype=float)))
    return iv / iv.sum()


def risk_contributions(w, cov):
    """Share of portfolio variance contributed by each asset (sums to 1)."""
    w = np.asarray(w, dtype=float)
    cov = np.asarray(cov, dtype=float)
    return w * (cov @ w) / (w @ cov @ w)


def erc_weights(cov, tol=1e-8):
    """Equal-risk-contribution weights, solved with scipy's fsolve (Spinu, 2013).

    ERC holds when x_i (S x)_i = 1/N for all i, i.e. when (S x)_i - 1/(N x_i) = 0: the first-order
    condition of the convex problem min 0.5 x'Sx - (1/N) sum(log x_i). We solve these N equations in
    log-coordinates x = exp(y) > 0, so the weights stay positive, and return w = x / sum(x).
    Returns (weights, ok). If the solution fails the check, inverse-vol weights are returned and ok=False.
    """
    cov = np.atleast_2d(np.asarray(cov, dtype=float))
    n = cov.shape[0]
    S = cov / np.mean(np.diag(cov))                 # rescale: the solution does not depend on the scale
    iv = 1.0 / np.sqrt(np.diag(S))
    x0 = iv / np.sqrt(iv @ S @ iv)                  # inverse-vol start, scaled so that x0' S x0 = 1

    def equations(y):
        x = np.exp(y)
        return S @ x - 1.0 / (n * x)

    def jacobian(y):                                # d equations_i / d y_j
        x = np.exp(y)
        return S * x[None, :] + np.diag(1.0 / (n * x))

    y, _info, ier, _msg = fsolve(equations, np.log(x0), fprime=jacobian, full_output=True, xtol=1e-12)
    w = np.exp(y)
    w = w / w.sum()
    ok = bool(ier == 1 and np.all(np.isfinite(w))
              and np.max(np.abs(risk_contributions(w, cov) - 1.0 / n)) < tol)
    if not ok:
        return inverse_vol_weights(cov), False
    return w, True


# ---------------------------------------------------------------- strategy: trend filter and target weights
def trend_signal(prices_m, window=10):
    """1.0 if the month-end price is above its `window`-month SMA (incl. the current month), 0.0 if not,
    NaN while the moving average is not yet available."""
    sma = prices_m.rolling(window, min_periods=window).mean()
    return (prices_m > sma).astype(float).where(sma.notna())


def first_decision_date(data, assets, cov_window=252, sma_window=10):
    """First month-end at which the covariance window and every moving average are complete."""
    assets = list(assets)
    px = data.prices_d[assets].dropna()
    first_cov = px.index[cov_window]                 # cov_window returns need cov_window + 1 prices
    first_sig = trend_signal(data.prices_m[assets], sma_window).dropna().index[0]
    months = data.prices_m.index
    return months[(months >= first_cov) & (months >= first_sig)][0]


def target_weights(data, assets, decision_dates, cov_window=252, sma_window=10,
                   use_trend=True, weighting="erc"):
    """Target weights decided at each month-end (rows) for the assets plus CASH (columns).

    Only information up to and including the decision date is used.
    """
    assets = list(assets)
    px = data.prices_d[assets].dropna()              # days on which all held ETFs trade
    rd = px.pct_change(fill_method=None).iloc[1:]
    sig = trend_signal(data.prices_m[assets], sma_window)
    rows, fallbacks = [], 0
    for t in decision_dates:
        window = rd.loc[:t].iloc[-cov_window:]
        if len(window) < cov_window:
            raise ValueError(f"{t.date()}: only {len(window)} daily returns available, need {cov_window}")
        cov = np.atleast_2d(np.cov(window.to_numpy(), rowvar=False))
        if weighting == "erc":
            w, ok = erc_weights(cov)
            fallbacks += int(not ok)
        elif weighting == "inverse_vol":
            w = inverse_vol_weights(cov)
        elif weighting == "equal":
            w = np.full(len(assets), 1.0 / len(assets))
        else:
            raise ValueError(f"unknown weighting '{weighting}'")
        w = pd.Series(w, index=assets, dtype=float)
        if use_trend:
            on = sig.loc[t, assets]
            if on.isna().any():
                raise ValueError(f"{t.date()}: trend signal not yet available")
            w = w.where(on == 1.0, 0.0)
        w["CASH"] = 1.0 - w.sum()
        rows.append(w.rename(t))
    W = pd.DataFrame(rows)
    W.index.name = "decision_date"
    W.attrs["fsolve_fallbacks"] = fallbacks
    return W


def constant_weights(weights, decision_dates):
    """Fixed-mix target weights (e.g. 60/40), rebalanced back to target at every decision date."""
    w = pd.Series(weights, dtype=float)
    if "CASH" not in w.index:
        w["CASH"] = 1.0 - w.sum()
    cols = [c for c in w.index if c != "CASH"] + ["CASH"]
    W = pd.DataFrame([w[cols].to_numpy()] * len(decision_dates),
                     index=pd.DatetimeIndex(decision_dates, name="decision_date"), columns=cols)
    W.attrs["fsolve_fallbacks"] = 0
    return W


# ---------------------------------------------------------------- backtest engine
def backtest(weights, data, cost_bps=10.0):
    """Monthly backtest: weights decided at month-end t earn the simple returns of month t+1.

    Holdings drift between rebalancing dates. Turnover = sum over ETFs of |target - drifted|.
    Costs = cost_bps/10,000 x turnover, deducted from portfolio value before the month's return.
    CASH earns the risk-free rate. Returns a DataFrame indexed by the month the return is earned in.
    """
    cols = list(weights.columns)
    assets = [c for c in cols if c != "CASH"]
    R = data.rets_m.reindex(columns=assets).copy()
    R["CASH"] = data.rf_m
    R = R[cols]
    months = data.rets_m.index
    drifted = pd.Series(0.0, index=cols)
    drifted["CASH"] = 1.0                            # the investor starts fully in cash
    rows = []
    for t, w in weights.iterrows():
        pos = months.get_loc(t)
        if pos + 1 >= len(months):                   # last decision: no next-month return yet
            break
        t_next = months[pos + 1]
        r = R.loc[t_next]
        if r[w > 0].isna().any():
            raise ValueError(f"missing return in {t_next.date()} for a held asset")
        r = r.fillna(0.0)
        turnover = float((w[assets] - drifted[assets]).abs().sum()) if assets else 0.0
        cost = cost_bps / 1e4 * turnover
        gross = float((w * r).sum())
        net = (1.0 - cost) * (1.0 + gross) - 1.0
        rows.append({"date": t_next, "gross": gross, "net": net, "turnover": turnover,
                     "cost": cost, "cash_weight": float(w["CASH"]), "rf": float(r["CASH"])})
        drifted = w * (1.0 + r) / (1.0 + gross)
    return pd.DataFrame(rows).set_index("date")


# ---------------------------------------------------------------- performance measures
def nav_from_returns(r, start=None):
    """Value of 1 invested at the decision date before the first return (the series starts at 1)."""
    r = r.dropna()
    if start is None:
        start = r.index[0] - pd.offsets.MonthEnd(1)
    nav = (1.0 + r).cumprod()
    return pd.concat([pd.Series([1.0], index=pd.DatetimeIndex([start])), nav]).rename(r.name)


def drawdown_series(r):
    nav = nav_from_returns(r)
    return nav / nav.cummax() - 1.0


def max_drawdown(r):
    return float(drawdown_series(r).min())


def capm_regression(excess, factor_excess, maxlags=4):
    """OLS of excess returns on factor excess returns -> (beta, monthly alpha, Newey-West t(alpha))."""
    df = pd.concat([excess, factor_excess], axis=1).dropna()
    X = sm.add_constant(df.iloc[:, 1].to_numpy())
    fit = sm.OLS(df.iloc[:, 0].to_numpy(), X).fit(cov_type="HAC", cov_kwds={"maxlags": maxlags})
    alpha, beta = fit.params
    return float(beta), float(alpha), float(fit.tvalues[0])


def performance_summary(r, rf, benchmark=None, market=None, turnover=None, periods=12, nw_lags=4):
    """All performance measures of the prospectus for one monthly return series."""
    r = r.dropna()
    rf = rf.reindex(r.index)
    ex = r - rf
    out = {
        "months": int(len(r)),
        "ann_mean": periods * r.mean(),
        "cagr": float(np.prod(1.0 + r) ** (periods / len(r)) - 1.0),
        "ann_vol": np.sqrt(periods) * r.std(ddof=1),
        "sharpe": periods * ex.mean() / (np.sqrt(periods) * ex.std(ddof=1)),
        "max_dd": max_drawdown(r),
        "worst_12m": float(((1.0 + r).rolling(12).apply(np.prod, raw=True) - 1.0).min()),
        "final_value": float(np.prod(1.0 + r)),
    }
    if market is not None:
        b, a, t = capm_regression(ex, market.reindex(r.index) - rf, nw_lags)
        out.update(beta_mkt=b, alpha_mkt=periods * a, alpha_mkt_t=t)
    if benchmark is not None:
        bench = benchmark.reindex(r.index)
        active = r - bench
        out["tracking_error"] = np.sqrt(periods) * active.std(ddof=1)
        out["info_ratio"] = (periods * active.mean() / out["tracking_error"]
                             if out["tracking_error"] > 0 else np.nan)
        b, a, t = capm_regression(ex, bench - rf, nw_lags)
        out.update(beta_bench=b, alpha_bench=periods * a, alpha_bench_t=t)
    if turnover is not None:
        out["turnover"] = periods * turnover.reindex(r.index).mean()
    return out


def breakeven_cost(diff, x0=10.0, max_bps=1000.0):
    """Cost level c (bps per unit turnover) with diff(c) = 0, solved with fsolve.

    `diff(c)` is e.g. Sharpe(strategy, c) - Sharpe(benchmark, c). Returns (c, ok); (nan, False) if the
    strategy is not ahead even at zero cost, so that no break-even exists.
    """
    if not diff(0.0) > 0:
        return np.nan, False
    sol, _info, ier, _msg = fsolve(lambda c: [diff(float(c[0]))], [x0], full_output=True)
    c = float(sol[0])
    ok = bool(ier == 1 and 0.0 <= c <= max_bps and abs(diff(c)) < 1e-8)
    return (c if ok else np.nan), ok


# ---------------------------------------------------------------- one call for notebook and app
def run_strategy(data, assets=None, cov_window=252, sma_window=10, use_trend=True, weighting="erc",
                 cost_bps=10.0, start_decision=None, end_decision=None, benchmark_weights=None):
    """Run the full strategy (and optionally a fixed-mix benchmark) over a common decision window."""
    assets = list(RISKY_ASSETS if assets is None else assets)
    if start_decision is None:
        start_decision = first_decision_date(data, assets, cov_window, sma_window)
    months = data.prices_m.index
    dates = months[months >= pd.Timestamp(start_decision)]
    if end_decision is not None:
        dates = dates[dates <= pd.Timestamp(end_decision)]
    W = target_weights(data, assets, dates, cov_window, sma_window, use_trend, weighting)
    res = backtest(W, data, cost_bps)
    out = {"weights": W, "result": res, "returns": res["net"].rename("Strategy"),
           "gross": res["gross"].rename("Strategy (gross)"), "start_decision": pd.Timestamp(dates[0]),
           "fsolve_fallbacks": W.attrs["fsolve_fallbacks"]}
    if benchmark_weights is not None:
        Wb = constant_weights(benchmark_weights, dates)
        resb = backtest(Wb, data, cost_bps)
        out["benchmark"] = resb["net"].rename("Benchmark")
        out["benchmark_result"] = resb
    return out


# ---------------------------------------------------------------- machine-learning extension: regime filter
logging.getLogger("hmmlearn").setLevel(logging.ERROR)   # silence "not converging" messages of single EM runs


@dataclass(frozen=True)
class HMMConfig:
    """All assumptions of the regime filter, fixed BEFORE looking at results (no tuning on the backtest)."""
    start: str = "1990-01-01"        # first day of the S&P 500 data used to train the HMM
    n_states: int = 2                # calm vs turbulent
    seeds: tuple = (0, 1, 2, 3, 4)   # EM restarts; the best one by TRAINING log-likelihood is kept
    n_iter: int = 100                # EM iterations per restart
    vol_window: int = 21             # trading days for realised volatility (feature)
    prob_threshold: float = 0.5      # risk-off if P(turbulent) > threshold
    risk_off_scale: float = 0.5      # growth assets are scaled to 50% in risk-off months
    vol_quantile: float = 0.8        # simple (non-ML) baseline: volatility above its 80th percentile so far
    stress_threshold: float = -0.05  # ex-post label: S&P 500 falls by more than 5% in the next month


HMM_CFG = HMMConfig()
GROWTH_ASSETS = ["SPY", "EFA", "VNQ", "DBC"]   # assets cut in risk-off months; IEF, GLD and T-bills are kept


def regime_features(prices, vol_window=21):
    """Daily features of the HMM: simple return and annualised realised volatility (past window only)."""
    r = prices.pct_change(fill_method=None)
    vol = r.rolling(vol_window).std() * np.sqrt(252)
    return pd.DataFrame({"ret": r, "vol": vol}).dropna()


def fit_hmm(X, cfg=HMM_CFG):
    """Gaussian HMM fitted with Baum-Welch (EM). Returns (model, scaler, index of the turbulent state).

    The scaler is fitted on the training data only. Several random starts guard against poor local optima;
    the run with the highest log-likelihood ON THE TRAINING DATA is kept. The turbulent state is defined by a
    fixed rule: the state with the higher mean volatility (no selection based on backtest results).
    """
    scaler = StandardScaler().fit(X)
    Z = scaler.transform(X)
    best = None
    for seed in cfg.seeds:
        model = GaussianHMM(n_components=cfg.n_states, covariance_type="full", n_iter=cfg.n_iter,
                            tol=1e-3, random_state=seed)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            model.fit(Z)
            ll = model.score(Z)
        if best is None or ll > best[0] + 1e-9:
            best = (ll, model)
    model = best[1]
    vol_means = scaler.inverse_transform(model.means_)[:, 1]
    return model, scaler, int(np.argmax(vol_means))


def filtered_state_probs(model, scaler, X):
    """Forward algorithm: P(state_t | observations up to t) for every t. Uses no future observations
    (unlike Viterbi or forward-backward smoothing over the whole sample)."""
    Z = scaler.transform(X)
    n = model.n_components
    log_b = np.column_stack([multivariate_normal.logpdf(Z, mean=model.means_[k], cov=model.covars_[k])
                             for k in range(n)])
    A = model.transmat_
    out = np.empty((len(Z), n))
    prev = model.startprob_
    for t in range(len(Z)):
        prior = model.startprob_ if t == 0 else prev @ A
        log_p = np.log(np.maximum(prior, 1e-300)) + log_b[t]
        p = np.exp(log_p - log_p.max())
        prev = out[t] = p / p.sum()
    return out


def map_years(step, features, items, cfg, n_jobs=1):
    """Run step(features, fit_year, dates, cfg) for every (fit_year, dates) item, in order.
    n_jobs != 1 uses joblib worker processes; where processes are not allowed (some sandboxes) it falls back
    to a serial loop. Results are identical either way."""
    if n_jobs != 1:
        try:
            return Parallel(n_jobs=n_jobs, return_as="generator")(
                delayed(step)(features, fy, ds, cfg) for fy, ds in items)
        except OSError:
            pass
    return (step(features, fy, ds, cfg) for fy, ds in items)


def _hmm_fit_filter(features, fit_year, dates, cfg):
    """One walk-forward step: fit on data up to 31 Dec of `fit_year`, filtered P(turbulent) at `dates`."""
    train = features.loc[:f"{fit_year}-12-31"]
    model, scaler, turb = fit_hmm(train.to_numpy(), cfg)
    upto = features.loc[:max(dates)]
    p = pd.Series(filtered_state_probs(model, scaler, upto.to_numpy())[:, turb], index=upto.index)
    return {t: float(p.loc[:t].iloc[-1]) for t in dates}


def hmm_regime_probs(features, decision_dates, cfg=HMM_CFG, progress=True, n_jobs=1):
    """Walk-forward P(turbulent) at each decision date.

    The HMM is re-estimated once a year on all data up to 31 December (expanding window). Every decision
    date t uses the latest model fitted on or before t and the filtered probability from data up to t.
    The yearly fits are independent, so `n_jobs` > 1 (or -1 = all cores) runs them in parallel; every fit
    has fixed seeds, so the result is identical for any n_jobs.
    """
    groups = {}
    for t in pd.DatetimeIndex(decision_dates):
        fit_year = t.year if (t.month == 12 and t.day == 31) else t.year - 1
        groups.setdefault(fit_year, []).append(t)
    items = list(groups.items())
    steps = map_years(_hmm_fit_filter, features, items, cfg, n_jobs)
    if progress:
        steps = tqdm(steps, total=len(items), desc="HMM walk-forward (one fit per year)")
    out = {}
    for step in steps:
        out.update(step)
    probs = pd.Series(out, name="p_turbulent").sort_index()
    probs.index.name = "decision_date"
    return probs


def vol_rule_signal(features, decision_dates, quantile=0.8):
    """Simple non-ML baseline: risk-off if today's realised volatility is above the `quantile` of all
    volatility observed so far (expanding window, past data only)."""
    vol = features["vol"]
    out = {}
    for t in pd.DatetimeIndex(decision_dates):
        hist = vol.loc[:t]
        out[t] = bool(hist.iloc[-1] > hist.quantile(quantile))
    sig = pd.Series(out, name="risk_off").sort_index()
    sig.index.name = "decision_date"
    return sig


def apply_risk_off(weights, risk_off, scale=0.5, growth_assets=None):
    """Scale the growth assets to `scale` of their weight in risk-off months and move the rest to T-bills."""
    growth = [a for a in (GROWTH_ASSETS if growth_assets is None else growth_assets) if a in weights.columns]
    W = weights.copy()
    off = risk_off.reindex(W.index).fillna(False).astype(bool).to_numpy()
    cut = W.loc[off, growth] * (1.0 - scale)
    W.loc[off, growth] = W.loc[off, growth] - cut
    W.loc[off, "CASH"] = W.loc[off, "CASH"] + cut.sum(axis=1)
    W.attrs = dict(weights.attrs)
    return W
